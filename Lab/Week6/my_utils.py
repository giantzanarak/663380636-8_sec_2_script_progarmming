def greet(name):
    """แสดงข้อความทักทายผู้ใช้ตามชื่อที่ส่งเข้ามา"""
    print(f"Hello, {name}! Welcome to my utility functions.")


def is_prime(number):
    """ตรวจสอบจำนวนเฉพาะ คืนค่า True ถ้า number เป็นจำนวนเฉพาะ และ False ถ้าไม่ใช่"""
    if number < 2:              # 0, 1 และเลขติดลบ ไม่ใช่จำนวนเฉพาะ
        return False

    # หารตั้งแต่ 2 ถึงรากที่สองของ number พอ ถ้าหารลงตัวแปลว่าไม่ใช่จำนวนเฉพาะ
    for i in range(2, int(number ** 0.5) + 1):
        if number % i == 0:
            return False

    return True


